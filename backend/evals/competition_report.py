"""Turn evals/model_competition.json into evals/COMPETITION_REPORT.md (readable tables, wins and losses).

  python -m evals.competition_report
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).parent
LABELS = {
    "ma28": "28-day moving average", "dow_mean_4w": "Same weekday, last 4 weeks",
    "ses_dow": "Exponential smoothing, weekday-adjusted", "tsb_dow": "TSB (intermittent demand)",
    "gbm": "Boosted trees (scikit-learn, base features)", "gbm_plus": "Boosted trees + 91-day level + days since sale",
    "gbm_plus_l2": "gbm_plus with squared-error loss", "gbm_plus_big": "gbm_plus with larger trees",
    "gbm_bag": "3 boosted models averaged (scikit-learn)",
    "lgb_poisson": "LightGBM, Poisson loss", "lgb_tweedie": "LightGBM, Tweedie loss",
    "xgb_poisson": "XGBoost, Poisson loss", "xgb_tweedie": "XGBoost, Tweedie loss",
    "ens_gbm_ses": "50% gbm_plus + 50% smoothing", "ens_gbm_ses_75": "75% gbm_plus + 25% smoothing",
    "ens_bag_ses_75": "75% gbm_bag + 25% smoothing (previous winner)", "ens_bag_tsb_75": "75% gbm_bag + 25% TSB",
    "ens_bag_ses": "50% gbm_bag + 50% smoothing", "ens_bag_ses_tsb": "50% gbm_bag + 25% smoothing + 25% TSB",
    "ens_gbms": "average of 3 boosted variants", "ens_all": "40% gbm_bag + 20% l2 + 20% big + 20% smoothing",
    "ens_lgb_ses_75": "75% LightGBM Tweedie + 25% smoothing", "ens_xgb_ses_75": "75% XGBoost Tweedie + 25% smoothing",
    "ens_bag_lgb_ses": "37.5% gbm_bag + 37.5% LightGBM + 25% smoothing",
    "ens_boost3_ses": "25% each: gbm_bag, LightGBM, XGBoost, smoothing",
}
DATASETS = {"favorita": "Favorita (Ecuador, store x family)", "m5": "Walmart M5 (USA, single items)",
            "rohlik": "Rohlik (Czechia/Hungary, item x warehouse)"}


def acc(w: float) -> str:
    return f"{(1 - w) * 100:.1f}%"


def main() -> None:
    res = json.loads((ROOT / "model_competition.json").read_text())
    sel, ds = res["selection"], res["datasets"]
    win = sel["winner"]
    names = [r["model"] for r in sel["ranking_on_validation"]]
    out = ["# Model competition: three real datasets", "",
           "Generated by `python -m evals.model_competition` and `python -m evals.competition_report`. "
           "None of the datasets is Indian; these results say nothing yet about accuracy in Indian shops.", "",
           "**Protocol.** Every candidate sees exactly the same history at each forecast origin. The winner is the "
           "single configuration with the best mean (over the three datasets) of weekly WAPE relative to a 28-day "
           "moving average on the VALIDATION windows; the later TEST windows were never used for choosing and are "
           "reported below. LightGBM and XGBoost settings were fixed before the first run.", "",
           f"**Winner: `{win}`** ({LABELS.get(win, win)}).", "",
           "## Ranking (relative weekly error vs 28-day moving average, lower is better)", "",
           "| Rank | Model | Validation | Test |", "|---|---|---|---|"]
    for i, r in enumerate(sel["ranking_on_validation"], 1):
        mark = "**" if r["model"] == win else ""
        out.append(f"| {i} | {mark}{LABELS.get(r['model'], r['model'])}{mark} | {r['val']:.4f} | {r['test']:.4f} |")
    out += ["", "## Held-out test windows, weekly accuracy (1 - WAPE)", "",
            "| Model | " + " | ".join(DATASETS[d] for d in ds) + " |", "|---|" + "---|" * len(ds)]
    show = [win] + [n for n in ("ens_bag_ses_75", "lgb_tweedie", "lgb_poisson", "xgb_tweedie", "xgb_poisson",
                                "gbm_bag", "ens_lgb_ses_75", "ens_boost3_ses", "tsb_dow", "ses_dow", "ma28") if n != win]
    for n in show:
        if n not in names:
            continue
        cells = [acc(ds[d]["test"][n]["wape_weekly"]) for d in ds]
        b = "**" if n == win else ""
        out.append(f"| {b}{LABELS.get(n, n)}{b} | " + " | ".join(cells) + " |")
    out += ["", "## Winner on every metric (test windows)", "",
            "| Dataset | Weekly WAPE | Daily WAPE | RMSSE | Bias |", "|---|---|---|---|---|"]
    for d in ds:
        s = ds[d]["test"][win]
        out.append(f"| {DATASETS[d]} | {s['wape_weekly']:.4f} | {s['wape_daily']:.4f} | {s['rmsse']:.4f} | {s['bias'] * 100:+.1f}% |")
    losses = res.get("winner_losses", [])
    out += ["", "## Where the winner loses", ""]
    if not losses:
        out.append("No candidate beat the winner on any dataset, split or metric.")
    else:
        out += ["Every dataset, window type and metric where at least one other candidate did better:", "",
                "| Dataset | Split | Metric | Winner | Best other | n better |", "|---|---|---|---|---|---|"]
        for l in losses:
            b = l["beaten_by"][0]
            out.append(f"| {d_name(l['dataset'])} | {l['split']} | {l['metric']} | {l['winner']:.4f} | "
                       f"{LABELS.get(b['model'], b['model'])}: {b['value']:.4f} | {l['n_better']} |")
    (ROOT / "COMPETITION_REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


def d_name(d: str) -> str:
    return DATASETS.get(d, d).split(" (")[0]


if __name__ == "__main__":
    main()
